import assert from 'node:assert/strict';
import {validTime,complete,reviewText} from './dist/logic.mjs';
assert(validTime('00:08'));
assert(validTime('01:02:30'));
assert(validTime('125:59'));
assert(validTime(''));
assert(!validTime('00:99'));
assert(!validTime('yesterday'));
const note={clip:'C01',version:'v02',time:'00:08',change:'Remove the intro.',priority:'Required change'};
assert(complete(note));
assert(!complete({...note,clip:''}));
assert(!complete({...note,change:' '}));
assert(!complete({...note,time:'00:99'}));
assert.equal(reviewText('','',[]),'');
const result=reviewText('Test batch','Sam',[note,{...note,change:''}]);
assert(result.includes('1 note'));
assert(!result.includes('2.'));
assert(result.includes('Final approver: Sam'));
assert(reviewText('','',[{...note,time:''}]).includes('Whole clip'));
assert(reviewText('','',[{...note,change:'<script>alert(1)</script>'}]).includes('<script>'));
console.log('16 assertions passed: timestamp validation, incomplete-note filtering, whole-clip notes, approver and text exports.');
